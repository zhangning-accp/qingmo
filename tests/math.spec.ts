import { test, expect } from '@playwright/test';

test('math renders, edits, roundtrips, cancels, rejects errors and stays literal in code', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('#startup')).toContainText('编辑就绪');
  await page.locator('#new').click(); await page.locator('#mode').click();
  const markdown = '计算 $(-2)\\times(-3)$<br>A. $6$\n\n$$\n\\frac{1}{2}\n$$\n\n`$literal$`';
  await page.locator('#source').fill(markdown); await page.locator('#mode').click();
  await expect(page.locator('[data-formula="math_inline"]')).toHaveCount(2);
  await expect(page.locator('[data-formula="math_block"] .katex')).toHaveCount(1);
  await expect(page.locator('.ProseMirror br')).not.toHaveCount(0);
  await expect(page.locator('.ProseMirror code')).toHaveText('$literal$');
  await page.locator('#mode').click(); await expect(page.locator('#source')).toHaveValue(markdown);
  await page.locator('#mode').click();
  await page.locator('[data-formula="math_inline"]').first().dblclick();
  const dialog = page.getByRole('dialog', { name: '编辑公式' });
  await expect(dialog).toBeVisible();
  await expect(page.locator('#formula-code')).toHaveValue('(-2)\\times(-3)');
  await page.locator('#formula-code').fill('\\frac{');
  await expect(page.locator('#formula-apply')).toBeDisabled();
  await page.locator('#formula-code').fill('x^{2}');
  await page.locator('#formula-apply').click();
  await expect(page.locator('[data-formula="math_inline"]').first()).toHaveAttribute('data-value', 'x^{2}');
  await page.locator('[data-formula="math_block"]').dblclick();
  await expect(page.locator('#formula-block')).toBeChecked();
  await page.keyboard.press('Escape'); await expect(dialog).toBeHidden();
  await page.locator('#mode').click();
  await expect(page.locator('#source')).toHaveValue(/x\^\{2\}/);
  await page.locator('#source').press('Control+End');
  await page.locator('#insert-formula').click();
  await page.locator('#formula-code').fill('\\sqrt{9}');
  await page.locator('#formula-block').check(); await page.locator('#formula-apply').click();
  await expect(page.locator('#source')).toHaveValue(/\$\$\n\\sqrt\{9\}\n\$\$/);
  await page.locator('#mode').click();
  await expect(page.locator('[data-formula="math_block"]')).toHaveCount(2);
  await page.locator('[data-formula="math_block"]').last().dblclick();
  await page.setViewportSize({ width: 760, height: 520 });
  const box = (await dialog.boundingBox())!;
  expect(box.x).toBeGreaterThanOrEqual(0);
  expect(box.x + box.width).toBeLessThanOrEqual(760);
  await page.locator('#formula-apply').scrollIntoViewIfNeeded();
  await expect(page.locator('#formula-apply')).toBeInViewport();
  await page.setViewportSize({ width: 1150, height: 800 });
  await page.screenshot({ path: 'qa/formula-editor.png' });
  await page.keyboard.press('Escape');
  await page.locator('#new').click();
  await page.locator('#insert-formula').click();
  await page.locator('#formula-code').fill('a^{2}+b^{2}');
  await page.locator('#formula-apply').click();
  await expect(page.locator('[data-formula="math_inline"]')).toHaveCount(1);
  await page.locator('.ProseMirror').click(); await page.keyboard.press('Control+z');
  await expect(page.locator('[data-formula="math_inline"]')).toHaveCount(0);
});
